// צורות מספר בעברית
export const clipsLabel = (n) => (n === 1 ? 'קליפ אחד' : `${n} קליפים`);
export const secondsLabel = (n) => (n === 1 ? 'שנייה אחת' : n === 2 ? 'שתי שניות' : `${n} שניות`);
export const minutesLabel = (n) => (n === 1 ? 'דקה' : n === 2 ? 'שתי דקות' : `${n} דקות`);

// "15 שניות", "דקה", "דקה וחצי"
export function lengthLabel(len) {
  if (len === 'auto') return 'אוטומטי';
  const n = Number(len);
  if (!Number.isFinite(n) || n <= 0) return 'אוטומטי';
  if (n === 60) return 'דקה';
  if (n === 90) return 'דקה וחצי';
  if (n % 60 === 0) return minutesLabel(n / 60);
  return `${n} שניות`;
}

// שעה:דקה:שנייה לתצוגה
export function clockText(sec) {
  const s = Math.max(0, Math.round(Number(sec) || 0));
  const h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), r = s % 60;
  const p = (x) => String(x).padStart(2, '0');
  return h ? `${h}:${p(m)}:${p(r)}` : `${m}:${p(r)}`;
}

// "5 MB" בתוך טקסט עברי: עוטפים בבידוד שמאל־לימין, כדי שלא יתהפך ל־"MB 5"
const ltr = (text) => `\u2066${text}\u2069`;
export function sizeText(bytes) {
  const b = Number(bytes) || 0;
  if (b <= 0) return ltr('0 KB');
  if (b < 1024 * 1024) return ltr(`${Math.max(1, Math.round(b / 1024))} KB`);
  if (b < 1024 * 1024 * 1024) return ltr(`${Math.round(b / (1024 * 1024))} MB`);
  return ltr(`${(b / (1024 * 1024 * 1024)).toFixed(1)} GB`);
}

// זמן משוער. בלי צורות זכר ונקבה ליחיד: "עוד בערך ..."
export function etaText(seconds) {
  if (seconds === null || seconds === undefined || !Number.isFinite(seconds)) return T.progress.etaSoon;
  const s = Math.max(0, seconds);
  if (s < 8) return 'עוד כמה שניות';
  if (s < 55) return `עוד בערך ${Math.round(s / 5) * 5} שניות`;
  if (s < 90) return 'עוד בערך דקה';
  const m = Math.round(s / 60);
  if (m < 60) return m === 2 ? 'עוד בערך שתי דקות' : `עוד בערך ${m} דקות`;
  const h = Math.floor(m / 60), rest = m % 60;
  return rest ? `עוד בערך ${h === 1 ? 'שעה' : h + ' שעות'} ו־${rest} דקות` : `עוד בערך ${h === 1 ? 'שעה' : h + ' שעות'}`;
}

